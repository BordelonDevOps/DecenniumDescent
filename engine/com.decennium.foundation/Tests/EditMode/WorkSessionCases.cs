        private sealed class WorkMutationPolicy : ICommandPolicy
        {
            private readonly string mode;private readonly TestOnlyWorkPolicy fixture=new TestOnlyWorkPolicy();
            public WorkMutationPolicy(string mode){this.mode=mode;}
            public string ContentFingerprint=>fixture.ContentFingerprint;public bool TestOnly=>true;
            public Snapshot Initial()=>fixture.Initial();public string ValidateState(Snapshot s)=>fixture.ValidateState(s);
            public string Resolve(Snapshot s,Command c)
            {
                fixture.Resolve(s,c);s.Work=s.Work.Consume(TestOnlyWorkPolicy.JobId,TestOnlyWorkPolicy.ClaimId);
                s.RuleClock=T(1,3);s.RandomState=270369;s.Actors[0].X=0;
                if(mode=="reject")return "InjectedRejection";
                if(mode=="throw")throw new InvalidOperationException("Injected policy failure.");
                if(mode=="invalid")s.Work=null;
                return null;
            }
        }
        private sealed class SchemaMutationPolicy : ICommandPolicy
        {
            private readonly bool upgrade;
            public SchemaMutationPolicy(bool upgrade){this.upgrade=upgrade;}
            public string ContentFingerprint=>"TEST_ONLY.schema-mutation";public bool TestOnly=>true;
            public Snapshot Initial(){var s=upgrade?new TestOnlyPolicy().Initial():new TestOnlyWorkPolicy().Initial();s.ContentFingerprint=ContentFingerprint;return s;}
            public string ValidateState(Snapshot s)=>null;
            public string Resolve(Snapshot s,Command c){s.SchemaVersion=upgrade?2:1;s.Work=upgrade?new WorkLedger():null;return null;}
        }
