        private static int FindMapping(byte[] bytes)
        {
            byte[] mapping=Encoding.UTF8.GetBytes(DiceStream.MappingVersion);
            for(int i=0;i<=bytes.Length-mapping.Length;i++)
                if(bytes.Skip(i).Take(mapping.Length).SequenceEqual(mapping)) return i;
            throw new Exception("Mapping tag absent.");
        }
