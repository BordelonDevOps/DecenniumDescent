"""Emit immutable source metadata from the reviewed bindings; no executable spell effects."""
import json
import hashlib
import sys
from pathlib import Path

packet = Path(__file__).resolve().parent
root = packet.parents[3]
binding = json.loads((packet / 'SELECTED_SPELL_BINDINGS.json').read_text(encoding='utf-8'))
catalog_bytes = (root / binding['catalogPath']).read_bytes()
assert hashlib.sha256(catalog_bytes).hexdigest() == binding['catalogSha256'], 'Pinned catalog bytes changed'
catalog = json.loads(catalog_bytes)['spells']
canonical_hash = lambda value: hashlib.sha256(json.dumps(value, sort_keys=True, separators=(',', ':'), ensure_ascii=False).encode()).hexdigest()
quote = lambda value: json.dumps(value, ensure_ascii=True)
rows = []
for spell in binding['selected']:
    card = catalog[int(spell['wholeCardPointer'].split('/')[-1])]
    assert card['id'] == spell['id'] and canonical_hash(card) == spell['wholeCardSha256']
    assert canonical_hash(card['operational']) == spell['procedureSha256']
    assert card['classAccess'] == spell['allClassAccess'] and card['additionalRpCost'] == spell['additionalRpCost']
    values = [spell[k] for k in ('id', 'name', 'wholeCardPointer', 'wholeCardSha256', 'procedureSha256',
                                 'originalCatalogRecordSha256', 'authoredReviewEntrySha256')]
    access = ',\n'.join('                    new SpellClassAccess(' + ', '.join([
        quote(name), quote(fact['school']), str(fact['rank']), str(fact['minimumClassLevel']), str(fact['baseRpCost'])]) + ')'
        for name, fact in sorted(spell['allClassAccess'].items()))
    placements = ',\n'.join('                    new SpellSourcePlacement(' + ', '.join([
        quote(fact['school']), str(fact['level']), quote(fact['summary'])]) + ')'
        for fact in spell['allSourcePlacements'])
    rows.append('            new SpellSourceDefinition(' + ', '.join(map(quote, values)) + ', ' + str(spell['additionalRpCost'])
        + ',\n                new[] {\n' + access + '\n                }, new[] {\n' + placements + '\n                })')
source = '''// Source metadata generated by the TAC-07 evidence packet; acquisition admission only.
using System;
using System.Collections.Generic;
using System.Linq;

namespace Decennium.Foundation
{
    public static class SpellSourceCatalog
    {
        public const string SourceRevision = "''' + binding['sourceRevision'] + '''";
        public const string CatalogPath = "''' + binding['catalogPath'] + '''";
        public const string CatalogSha256 = "''' + binding['catalogSha256'] + '''";
        public const string ClassProgressionSha256 = "42ab857dc9a90d1233ab3d436e712d19b113293dd926a1624da6527be283a64a";
        public static IReadOnlyList<SpellSourceDefinition> Definitions { get; } = Array.AsReadOnly(new[] {
''' + ',\n'.join(rows) + '''
        });
        public static SpellSourceDefinition Get(string id) => Definitions.SingleOrDefault(x => x.Id == id);
    }
}
'''
output = root / 'engine/com.decennium.foundation/Runtime/Core/SpellSourceCatalog.cs'
if '--check' in sys.argv:
    assert output.read_bytes() == source.encode('utf-8'), 'Generated runtime registry differs from reviewed bindings'
    print('PASS: 6 exact source bindings and unchanged generated runtime registry.')
else:
    output.write_bytes(source.encode('utf-8'))
    print('Generated 6 exact source bindings, preserving every class access and school placement.')
