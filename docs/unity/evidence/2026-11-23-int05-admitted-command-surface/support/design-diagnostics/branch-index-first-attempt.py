"""Reconcile finite family plans against the unchanged admission axes."""
import hashlib,json
from pathlib import Path
P=Path(__file__).resolve().parent
def read(n): return json.loads((P/n).read_text(encoding='utf-8'))
names=['PHYSICAL_TACTICAL_BRANCH_QUALIFICATION_PLAN.json','MAGIC_AND_CARE_BRANCH_QUALIFICATION_PLAN.json','MANAGEMENT_BRANCH_QUALIFICATION_PLAN.json']
inventory=read('OPERATION_INVENTORY.json')
expected={x['kind']:x['semanticBranchesToDisposition'] for x in inventory['operations']}
rows={};inputs=[]
for name in names:
    doc=read(name)
    inputs.append({'path':name,'sha256':hashlib.sha256((P/name).read_bytes()).hexdigest()})
    for oi,op in enumerate(doc['operations']):
        kind=op['kind'];assert kind not in rows
        if name.startswith('MANAGEMENT'):
            axes=[(i,a) for i,a in enumerate(doc['axes']) if a['kind']==kind]
            pointers=[{'axis':a['axis'],'allocation':f'{name}#/axes/{i}','expectedBehavior':a['nativeExpectedBehavior'],'routeIds':a['finiteRouteIds'],'disposition':a['qualificationDisposition']} for i,a in axes]
        else:
            pointers=[{'axis':a['axis'],'allocation':f'{name}#/operations/{oi}/axes/{ai}','expectedBehavior':a.get('expected',a.get('sourceDerivedExpectedBehavior')),'routeIds':a['routeIds'],'disposition':a.get('classification',a.get('allocationStatus'))} for ai,a in enumerate(op['axes'])]
        assert [a['axis'] for a in pointers]==expected[kind],kind
        assert all(a['expectedBehavior'] and a['routeIds'] for a in pointers),kind
        rows[kind]={'kind':kind,'operationPlan':f'{name}#/operations/{oi}','axes':pointers,'executed':False}
assert rows.keys()==expected.keys()
result={'schemaVersion':1,'status':'ALL_UNCHANGED_CANDIDATE_AXES_ALLOCATED_TO_FINITE_SOURCE_PLANS_NOT_EXECUTED',
        'counts':{'candidateKinds':len(rows),'candidateAxes':sum(len(x['axes']) for x in rows.values()),'operatorKinds':2,'newApiQualifiedBranches':0},
        'inputs':inputs,'operations':[rows[o['kind']] for o in inventory['operations']],
        'operatorKinds':[{'kind':op['kind'],'allocation':f'{names[0]}#/operatorOperations/{i}','executed':False} for i,op in enumerate(read(names[0])['operatorOperations'])],
        'profileAndCheckpointPlan':'PROFILE_AND_CHECKPOINT_QUALIFICATION_PLAN.json',
        'preservedLimits':['Each state-changing route/alternative requires all five complete paths under original factory/arguments.','Genuine producer gaps and model/detached controls stay explicit in each plan; allocation is not acceptance or observed reachability.','Use frozen source expectations and exact current field predicates; no expected value is generated by the new projection under test.','Current native constructor canonicalization controls request identity; reversed caller lists that canonicalize equally are not separate gameplay branches.'],
        'sourceApiAccepted':False,'runtimeAuthorized':False}
assert result['counts']['candidateAxes']==204
(P/'BRANCH_QUALIFICATION_INDEX.json').write_text(json.dumps(result,indent=2,ensure_ascii=False)+'\n',encoding='utf-8')
print(json.dumps(result['counts']))
